    /// **Every reading trait this crate declares has a real end in the
    /// application**, and the claim is checked rather than asserted.
    ///
    /// **This replaces the record that used to stand here.** Until 2026-09-04
    /// this crate carried a list of its own readings that nothing implemented
    /// outside test code, and the test asked that the list and the code agree.
    /// **The acting half gave both of them real ends, so the list came off and
    /// what is left is the stronger claim**: not that the record is honest, but
    /// that there is nothing for it to record.
    ///
    /// **The record is a claim about the whole application, so the test reads
    /// the whole application** — every `.rs` file under the `src` tree of every
    /// member named by the workspace manifest at `App/Cargo.toml`, this crate
    /// included, with the member list read rather than written here.
    ///
    /// **What it cannot see.** It reads text and compiles nothing, so an
    /// implementation written by a macro or named through an alias is not found.
    /// `#[cfg(test)]` is taken as beginning test code and running to the end of
    /// the file, which is where every file in this workspace puts it. And a
    /// crate that is not a workspace member is not read, deliberately: what is
    /// not built is not part of the application.
    #[test]
    fn every_reading_this_crate_declares_has_a_real_end() {
        let mut declared = Vec::new();
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        for (_, text) in every_rust_file_under(&src) {
            for line in text.lines() {
                if let Some(rest) = line.trim_start().strip_prefix("pub trait ") {
                    declared.push(
                        rest.split_whitespace()
                            .next()
                            .unwrap_or_default()
                            .to_string(),
                    );
                }
            }
        }
        assert!(
            declared.len() >= 3,
            "this crate's traits were not found: {declared:?}"
        );

        let implemented = what_the_application_implements();
        for trait_name in &declared {
            let ends: Vec<&String> = implemented
                .iter()
                .filter(|(held, _)| held == trait_name)
                .map(|(_, where_it_is)| where_it_is)
                .collect();
            assert!(
                !ends.is_empty(),
                "{trait_name} is a reading this crate declares and nothing in the \
                 application implements it outside test code"
            );
        }
    }


    /// **The marker rule, held rather than remembered.**
    ///
    /// **This is the settled shape, and it is the one the crates still to be
    /// written copy.** Settled 2026-09-04, out of the step 6 gate, which found
    /// two blind spots in the version that stood here. The file walk that feeds
    /// it recurses and asserts an exact count, which is the second blind spot and
    /// is at [`every_file`].
    ///
    /// Five things fail here, over every file of this crate including its front
    /// matter.
    ///
    /// - **A bare marker belonging to another document.** `M1` is defined in
    ///   eight documents, so a bare one does not fail to resolve: it resolves to
    ///   a real and wrong clause. A bare marker is allowed only where this plan
    ///   defines it, or where the file's own header list names it.
    /// - **A marker written with a document that does not define it.** That is
    ///   the wrongly-attributed case, and it reads exactly like a right one.
    /// - **A header list naming a marker this plan also defines.** Where a marker
    ///   is a clause of this crate's plan *and* of the document meant, **the
    ///   header list is not enough** and the document is written out at the site —
    ///   because a bare use could then mean either. This crate carried seventeen
    ///   such sites until 2026-09-04 and nothing could tell them apart.
    /// - **A header list naming a marker the document it is filed under does not
    ///   define.** **The first blind spot the gate found: the header list was an
    ///   unchecked whitelist.** Every marker in it was flattened into one list and
    ///   any bare marker in the body that appeared there was forgiven, whatever
    ///   document it was filed under. This crate filed two markers under
    ///   `Rented-server runtime` whose prefixes that plan does not define at all,
    ///   and both survived a gate run: the body use read as bare, and bare was
    ///   forgiven by the list.
    /// - **A header entry filed under no document at all**, which the list's own
    ///   heading forbids: each marker is named with the document it belongs to.
    ///
    /// **What it cannot see, said rather than glossed. Three traps, and each has
    /// already caught somebody.**
    ///
    /// - **The scan is line-based and compiles nothing.** A marker inside a name
    ///   with an underscore in it is skipped, and so is one reached through a
    ///   link rather than written out.
    /// - **A capital followed by a digit is not a marker's shape.** That test
    ///   matches `Blender5` inside a derived path, which puts the attribution leg
    ///   on prose. [`looks_like_a_marker`] is the settled shape and is tighter.
    /// - **A plan's name broken across two comment lines reads with a double
    ///   space** unless every line is trimmed before it is joined — and a name
    ///   with a double space in it matches no plan, so a correct citation is
    ///   called unattributed. [`split_off_the_header_list`] trims both halves.
    ///
    /// And it cannot tell a bare marker that means this plan's clause from one
    /// that means a colliding clause of a document named earlier in the same
    /// sentence — **which is why `lib.rs` makes writing the document out at the
    /// site the rule for a collision, and why the third leg above forbids the
    /// header list from standing in for that.**
    #[test]
    fn no_marker_stands_bare_that_is_not_this_plans_and_none_is_wrongly_attributed() {
        let dictionary = the_marker_dictionary();
        let plans: Vec<String> = dictionary.iter().map(|(name, _)| name.clone()).collect();
        let mine: Vec<String> = the_clauses_this_plan_defines()
            .into_iter()
            .map(|(_, marker)| marker)
            .collect();

        let mut bare = Vec::new();
        let mut wrong = Vec::new();
        let mut in_the_header = Vec::new();
        for (file, text, header) in every_file(true) {
            let filed = the_header_list_by_document(&header, &plans);
            let named_in_the_header: Vec<String> =
                filed.iter().map(|(_, marker)| marker.clone()).collect();
            for (document, marker) in &filed {
                match document {
                    None => in_the_header.push(format!(
                        "{file}: {marker} is filed under no document — the list names each \
                         marker with the document it belongs to"
                    )),
                    Some(document) => {
                        let defines = dictionary
                            .iter()
                            .find(|(name, _)| name == document)
                            .map(|(_, markers)| markers.contains(marker))
                            .unwrap_or(false);
                        if !defines {
                            in_the_header.push(format!(
                                "{file}: {marker} is filed under `{document}`, which does not \
                                 define it"
                            ));
                        }
                    }
                }
                if mine.contains(marker) {
                    in_the_header.push(format!(
                        "{file}: {marker} is in the header list and this plan also defines it — \
                         write the document out at the site instead"
                    ));
                }
            }
            for (marker, document) in the_markers_in(&text, &plans) {
                match document {
                    None => {
                        if !mine.contains(&marker) && !named_in_the_header.contains(&marker) {
                            bare.push(format!("{file}: {marker}"));
                        }
                    }
                    Some(document) => {
                        let defines = dictionary
                            .iter()
                            .find(|(name, _)| *name == document)
                            .map(|(_, markers)| markers.contains(&marker))
                            .unwrap_or(false);
                        if !defines {
                            wrong.push(format!("{file}: `{document}` {marker}"));
                        }
                    }
                }
            }
        }
        assert!(
            bare.is_empty(),
            "these markers stand bare, are not clauses of this plan, and are not in \
             their file's header list — a bare marker resolves to a real and wrong \
             clause: {bare:?}"
        );
        assert!(
            wrong.is_empty(),
            "these markers are written with a document that does not define them: {wrong:?}"
        );
        assert!(in_the_header.is_empty(), "{in_the_header:#?}");
    }

    /// **A document's name governs the marker immediately after it and no
    /// further**, so every later marker in the same run is read as that
    /// document's and resolves to the wrong clause.
    ///
    /// Returns each run of markers that follows a backticked plan name, as
    /// (file, plan, markers in the run after the first).
    ///
    /// **A run is markers joined by nothing but separators** — a space, a
    /// comma, `and`, `or`, a dash, `to`. Anything else ends it, so a marker
    /// in the next sentence is not swept up and a bolded run that closes
    /// after the first marker is not read past.
    fn the_runs_after_a_document_name(
        text: &str,
        plan_names: &[String],
    ) -> Vec<(String, Vec<String>)> {
        let bytes = text.as_bytes();
        let mut out = Vec::new();
        let mut at = 0;
        while at < bytes.len() {
            if bytes[at] != b'`' {
                at += 1;
                continue;
            }
            let Some(closes) = text[at + 1..].find('`').map(|found| at + 1 + found) else {
                break;
            };
            let named = text[at + 1..closes].to_string();
            at = closes + 1;
            if !plan_names.contains(&named) {
                continue;
            }
            // The run: marker, separator, marker, separator, … Anything that is
            // neither ends it.
            let mut run: Vec<String> = Vec::new();
            let mut rest = &text[at..];
            loop {
                let rest_trimmed = rest.trim_start_matches(' ');
                let word: String = rest_trimmed
                    .chars()
                    .take_while(char::is_ascii_alphanumeric)
                    .collect();
                if word.is_empty() || !looks_like_a_marker(&word) {
                    break;
                }
                let mut after = &rest_trimmed[word.len()..];
                // A marker inside a name with an underscore in it is not a
                // citation, and the outer guard already skips one.
                if after.starts_with('_') {
                    break;
                }
                run.push(word);
                // A marker's own possessive is part of the citation.
                after = after.strip_prefix("'s").unwrap_or(after);
                // Exactly the separators a list of citations is written with.
                // Anything else — a full stop, a bold run closing, a word —
                // ends the run.
                let stepped = after
                    .strip_prefix(',')
                    .unwrap_or(after)
                    .trim_start_matches(' ');
                let stepped = ["and ", "or ", "to ", "– ", "- "]
                    .iter()
                    .find_map(|joiner| stepped.strip_prefix(joiner))
                    .unwrap_or(stepped);
                let separated = stepped.len() < after.len();
                if !separated {
                    break;
                }
                rest = stepped;
            }
            if run.len() > 1 {
                out.push((named, run[1..].to_vec()));
            }
        }
        out
    }

    /// **The neighbour rule, held rather than remembered: a document's name
    /// governs the marker immediately after it and lends itself to no
    /// other.**
    ///
    /// This is the class the guard above cannot see, named in its own list of
    /// limits: *"it cannot tell a bare marker that means this plan's clause
    /// from one that means a colliding clause of a document named earlier in
    /// the same sentence"*. On 2026-09-04 two citations in one crate each
    /// paired a plan's name with two markers, and in both pairs the second
    /// was one that plan does not define. The guard above forgave both: it
    /// read each second marker as bare, and a bare marker this plan defines
    /// is what it allows. The eye, meanwhile, takes the name as governing
    /// both. **No example is written out here on purpose** — a real plan's
    /// name beside a marker it does not define is the very fault this leg
    /// reports, and every leg reads this file too.
    ///
    /// **A marker in such a run that the named document does not define is a
    /// fault whatever it means**, and the fix is always the same: write the
    /// document out at the site, this plan's own name included.
    ///
    /// **What it cannot see.** A run that the named document *does* define
    /// every marker of is passed, which is right; and a marker separated from
    /// the run by anything but a plain separator is not in the run at all, so
    /// a citation spread across a clause is not reached.
    #[test]
    fn a_document_name_governs_only_the_run_it_opens_and_lends_itself_to_none() {
        let dictionary = the_marker_dictionary();
        let plans: Vec<String> = dictionary.iter().map(|(name, _)| name.clone()).collect();

        let mut faults = Vec::new();
        for (file, text, header) in every_file(true) {
            for part in [&text, &header] {
                for (document, run) in the_runs_after_a_document_name(part, &plans) {
                    let defines = dictionary
                        .iter()
                        .find(|(plan, _)| *plan == document)
                        .map(|(_, markers)| markers.clone())
                        .unwrap_or_default();
                    for marker in run {
                        if !defines.contains(&marker) {
                            faults.push(format!(
                                "{file}: {marker} stands in a run opened by `{document}`, \
                                 which does not define it — the name governs only the marker \
                                 after it, so write this one's document out"
                            ));
                        }
                    }
                }
            }
        }
        assert!(faults.is_empty(), "{faults:#?}");
    }


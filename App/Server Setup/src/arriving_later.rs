    /// Whether a word has a clause marker's shape.
    ///
    /// **One or two letters, one or two digits, and at most two trailing lower
    /// case letters** — this plan's own `M1a`, `B12a`, `S7b` and `Y4a`, and
    /// `Keys` U7ab.
    ///
    /// **It is deliberately tighter than a capital-plus-a-digit test**, which
    /// matches `Blender5` in a derived path and would put the attribution test
    /// below on prose rather than on a marker.
    fn looks_like_a_marker(word: &str) -> bool {
        let bytes = word.as_bytes();
        if bytes.is_empty() || !bytes[0].is_ascii_uppercase() {
            return false;
        }
        let mut at = 1;
        if at < bytes.len() && bytes[at].is_ascii_alphabetic() {
            at += 1;
        }
        let digits_from = at;
        while at < bytes.len() && bytes[at].is_ascii_digit() {
            at += 1;
        }
        if !(1..=2).contains(&(at - digits_from)) {
            return false;
        }
        let mut tail = 0;
        while at < bytes.len() && bytes[at].is_ascii_lowercase() && tail < 2 {
            at += 1;
            tail += 1;
        }
        at == bytes.len()
    }

    /// Every clause a plan defines, as (top-level section, marker), in the
    /// plan's own order.
    ///
    /// **The heading's number keeps its letter** — `9b` is a top-level section
    /// of this plan and reading only its digits would file `F1` to `F3` under
    /// §9 beside the elevation clauses.
    fn the_clauses_a_plan_defines(text: &str) -> Vec<(String, String)> {
        let mut heading = "";
        let mut out = Vec::new();
        for line in text.lines() {
            if let Some(rest) = line.strip_prefix("### ") {
                heading = rest;
            } else if let Some(rest) = line.strip_prefix("## ") {
                heading = rest;
            }
            let number = heading
                .split_whitespace()
                .next()
                .unwrap_or_default()
                .trim_end_matches('.');
            let top = number.split('.').next().unwrap_or_default();
            if top.is_empty() || !top.starts_with(|c: char| c.is_ascii_digit()) {
                continue;
            }
            let body = line
                .trim_start()
                .trim_start_matches("- ")
                .trim_start_matches("* ");
            let Some(rest) = body.strip_prefix("**") else {
                continue;
            };
            let marker: String = rest.chars().take_while(char::is_ascii_alphanumeric).collect();
            // The marker is followed by its own punctuation or a space; a
            // bolded sentence beginning with an ordinary word is not one.
            let after = rest[marker.len()..].chars().next().unwrap_or(' ');
            if looks_like_a_marker(&marker) && matches!(after, '.' | ' ' | ',' | ':' | '*' | '—') {
                out.push((top.to_string(), marker));
            }
        }
        out
    }

    fn the_clauses_this_plan_defines() -> Vec<(String, String)> {
        the_clauses_a_plan_defines(THE_PLAN)
    }


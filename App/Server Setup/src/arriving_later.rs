    /// The file's text with the comment markers off so a citation that wrapped
    /// over a line break reads as one sentence, and with the header list of
    /// other documents' markers pulled out into its own run.
    ///
    /// **Every line of both halves is trimmed before it is joined, and joined
    /// with exactly one space.** A document's name broken across two comment
    /// lines otherwise reads with a double space in it, matches no plan, and
    /// turns a correct citation into an unattributed one.
    fn split_off_the_header_list(text: &str) -> (String, String) {
        let mut body = String::new();
        let mut header = String::new();
        let mut in_the_header_list = false;
        for line in text.lines() {
            let line = line.trim();
            if line.contains("Markers used") {
                in_the_header_list = true;
            }
            if in_the_header_list {
                match line.strip_prefix("//!").or_else(|| line.strip_prefix("///")) {
                    // **The list ends at the first empty comment line**, so a file
                    // may follow it with a note saying which markers it
                    // deliberately does not list and why. A note inside the list
                    // would put those markers back into it.
                    Some(rest) if !rest.trim().is_empty() => {
                        header.push_str(rest.trim());
                        header.push(' ');
                        continue;
                    }
                    _ => in_the_header_list = false,
                }
            }
            let line = line
                .strip_prefix("///")
                .or_else(|| line.strip_prefix("//!"))
                .or_else(|| line.strip_prefix("//"))
                .unwrap_or(line);
            body.push_str(line.trim());
            body.push(' ');
        }
        (body, header)
    }

    /// The header list read **as segments rather than as one flat list**: each
    /// entry is a marker with the document whose name last opened a segment.
    ///
    /// **A header list is written as a plan's name in backticks followed by that
    /// plan's markers, then the next plan's name and its markers**, so a
    /// backticked plan name opens a segment and every marker after it belongs to
    /// that plan until the next name. **Reading the list flat is what
    /// let a wrongly attributed marker through**: the flat list forgave any bare
    /// marker in the body that appeared anywhere in the header, whatever document
    /// it was filed under, and nothing ever asked whether that document defines
    /// it.
    ///
    /// A marker standing before any plan name carries `None` and is a fault of
    /// its own — the list's own heading says each marker is named with the
    /// document it belongs to.
    fn the_header_list_by_document(
        header: &str,
        plans: &[String],
    ) -> Vec<(Option<String>, String)> {
        let mut out = Vec::new();
        let mut current: Option<String> = None;
        let bytes = header.as_bytes();
        let mut at = 0;
        while at < bytes.len() {
            if bytes[at] == b'`' {
                let Some(closes) = header[at + 1..].find('`').map(|found| at + 1 + found) else {
                    break;
                };
                let named = &header[at + 1..closes];
                if let Some(plan) = plans.iter().find(|plan| plan.as_str() == named) {
                    current = Some(plan.clone());
                }
                at = closes + 1;
                continue;
            }
            if bytes[at].is_ascii_alphanumeric() {
                let mut end = at;
                while end < bytes.len() && bytes[end].is_ascii_alphanumeric() {
                    end += 1;
                }
                let word = &header[at..end];
                if looks_like_a_marker(word) {
                    out.push((current.clone(), word.to_string()));
                }
                at = end;
                continue;
            }
            at += 1;
        }
        out
    }

    /// The plan whose name stands immediately before the marker at `at`, where
    /// one does.
    ///
    /// **By the rule this crate states in `lib.rs`, a marker with nothing
    /// backticked before it means a clause of this crate's own plan.**
    fn the_document_beside_it(text: &str, at: usize, plans: &[String]) -> Option<String> {
        let before = text[..at]
            .trim_end()
            .trim_end_matches(|c: char| "*([{\"'".contains(c))
            .trim_end();
        let inner = before.strip_suffix('`')?;
        let opens = inner.rfind('`')?;
        let named = &inner[opens + 1..];
        plans.iter().find(|plan| *plan == named).cloned()
    }

    /// Every marker-shaped word in a file's text, as (marker, the document
    /// beside it where there is one, the byte it starts at).
    fn the_markers_in(text: &str, plans: &[String]) -> Vec<(String, Option<String>)> {
        let bytes = text.as_bytes();
        let mut out = Vec::new();
        let mut at = 0;
        while at < bytes.len() {
            let starts_a_word = bytes[at].is_ascii_uppercase()
                && (at == 0 || !(bytes[at - 1].is_ascii_alphanumeric() || bytes[at - 1] == b'_'));
            if !starts_a_word {
                at += 1;
                continue;
            }
            let mut end = at;
            while end < bytes.len() && bytes[end].is_ascii_alphanumeric() {
                end += 1;
            }
            let word = &text[at..end];
            let runs_into_an_identifier = end < bytes.len() && bytes[end] == b'_';
            if looks_like_a_marker(word) && !runs_into_an_identifier {
                out.push((word.to_string(), the_document_beside_it(text, at, plans)));
            }
            at = end.max(at + 1);
        }
        out
    }

